def build_ginkgo_dataset(data_cfg, logger=None):
    """
    构建银杏树数据集

    Args:
        data_cfg: 数据配置字典
        logger: 日志器

    Returns:
        dataset: GinkgoDataset 实例
    """
    _cfg = data_cfg.copy()
    if 'type' in _cfg:
        _cfg.pop('type')
    _cfg['logger'] = logger
    return GinkgoDataset(**_cfg)


def build_ginkgo_dataloader(dataset, batch_size=1, num_workers=1, training=True, dist=False):
    """
    构建数据加载器

    Args:
        dataset: 数据集实例
        batch_size: 批大小
        num_workers: 工作进程数
        training: 是否训练模式
        dist: 是否分布式训练

    Returns:
        dataloader: DataLoader 实例
    """
    from torch.utils.data import DataLoader

    shuffle = training
    sampler = None

    if dist:
        from torch.utils.data.distributed import DistributedSampler
        sampler = DistributedSampler(dataset, shuffle=shuffle)
        shuffle = False
    elif training and getattr(dataset, 'balance_domains', False):
        from collections import Counter
        from torch.utils.data import WeightedRandomSampler

        def domain_name(filename):
            name = osp.basename(filename).lower()
            for domain in ('culs', 'nibio', 'rmit', 'scion', 'tuwien'):
                if domain in name:
                    return domain
            return 'unknown'

        domains = [domain_name(filename) for filename in dataset.filenames]
        counts = Counter(domains)
        weights = torch.as_tensor(
            [1.0 / counts[domain] for domain in domains], dtype=torch.double
        )
        sampler = WeightedRandomSampler(
            weights, num_samples=len(weights), replacement=True
        )
        shuffle = False

    if training:
        return DataLoader(
            dataset,
            batch_size=batch_size,
            num_workers=num_workers,
            collate_fn=dataset.collate_fn,
            shuffle=shuffle,
            sampler=sampler,
            drop_last=True,
            pin_memory=True
        )
    else:
        return DataLoader(
            dataset,
            batch_size=batch_size,
            num_workers=num_workers,
            collate_fn=dataset.collate_fn,
            shuffle=False,
            sampler=sampler,
            drop_last=False,
            pin_memory=True
        )


