"""
银杏树数据集 - 边界引导实例分割版本
=====================================

适配 BoundaryGuidedSegmentation 模型，支持：
- TreeLearn 风格的 Verticality 和实例中心计算
- 边界标签 (boundary_labels)
- HDBSCAN 聚类所需的数据

数据格式支持：
- 4元组: (xyz, rgb, semantic_label, instance_label)
- 6元组: (xyz, rgb, semantic_label, instance_label, room_label, scene_name)
- 7元组: (xyz, rgb, semantic_label, instance_label, verticality, room_label, scene_name)
- 8元组: (xyz, rgb, semantic_label, instance_label, verticality, boundary_labels, room_label, scene_name)
"""

import math
import json
import os.path as osp
from pathlib import Path
from glob import glob
import numpy as np
import scipy.interpolate
import scipy.ndimage
import torch
from torch.utils.data import Dataset


class GinkgoDataset(Dataset):
    """
    银杏树数据集 - 边界引导实例分割版本
    
    类别定义：
    - 语义类别：other (0), ginkgo (1)
    - 实例类别：ginkgo (0) - 只有银杏树参与实例分割
    - sem2ins_classes: [1] - 语义标签1对应实例分割
    """
    
    # 实例分割类别
    CLASSES = ('ginkgo',)
    NYU_ID = None
    
    # 语义分割类别
    SEMANTIC_CLASSES = ('other', 'ginkgo')
    
    # 前景类别
    SEM2INS_CLASSES = [1]  # ginkgo 的语义标签
    
    # TreeLearn 风格参数
    TREE_BASE_HEIGHT = 0.5
    MIN_POINTS_FOR_ROBUST_Z = 11

    def __init__(self,
                 data_root,
                 prefix,
                 suffix,
                 voxel_cfg=None,
                 training=True,
                 with_label=True,
                 repeat=1,
                 boundary_label_power=1.0,
                 balance_domains=False,
                 file_list=None,
                 logger=None):
        """
        Args:
            data_root: 数据根目录
            prefix: 子目录名 (如 'train', 'val')
            suffix: 文件后缀
            voxel_cfg: 体素化配置
            training: 是否训练模式
            with_label: 是否包含标签
            repeat: 数据重复次数
            logger: 日志器
        """
        self.data_root = data_root
        self.prefix = prefix
        self.suffix = suffix
        self.voxel_cfg = voxel_cfg
        self.training = training
        self.with_label = with_label
        self.repeat = repeat
        if boundary_label_power <= 0:
            raise ValueError('boundary_label_power must be positive')
        self.boundary_label_power = float(boundary_label_power)
        self.balance_domains = bool(balance_domains)
        self.file_list = file_list
        self.logger = logger
        self.mode = 'train' if training else 'test'
        
        self.filenames = self.get_filenames()
        if self.logger:
            self.logger.info(f'Load {self.mode} dataset: {len(self.filenames)} scans')
        else:
            print(f'Load {self.mode} dataset: {len(self.filenames)} scans')

    def get_filenames(self):
        """获取所有数据文件名"""
        if self.file_list:
            payload = json.loads(Path(self.file_list).read_text(encoding='utf-8'))
            filenames = [str(Path(path)) for path in payload]
            missing = [path for path in filenames if not Path(path).is_file()]
            if missing:
                raise FileNotFoundError(
                    f'missing files from file_list: {missing[:3]}'
                )
        else:
            filenames = glob(osp.join(self.data_root, self.prefix, '*' + self.suffix))
        assert len(filenames) > 0, f'Empty dataset at {osp.join(self.data_root, self.prefix)}'
        filenames = sorted(filenames * self.repeat)
        return filenames

    def __len__(self):
        return len(self.filenames)

    @staticmethod
    def _to_numpy(value, dtype=None):
        """Accept both legacy NumPy tuples and portable tensor tuples."""
        if isinstance(value, torch.Tensor):
            value = value.detach().cpu().numpy()
        else:
            value = np.asarray(value)
        if dtype is not None:
            value = value.astype(dtype, copy=False)
        return value

    def load(self, filename):
        """
        加载数据文件
        
        支持多种数据格式，返回统一的6元组
        """
        try:
            # Explicitly allow the trusted, legacy NumPy tuples generated by
            # prepare_with_verticality.py. PyTorch 2.6 changed this default.
            data = torch.load(filename, map_location='cpu', weights_only=False)
        except TypeError:
            data = torch.load(filename, map_location='cpu')

        if self.with_label:
            if len(data) == 4:
                xyz, rgb, semantic_label, instance_label = data
                verticality = np.zeros(len(xyz), dtype=np.float32)
                boundary_labels = np.zeros(len(xyz), dtype=np.float32)
            elif len(data) == 6:
                xyz, rgb, semantic_label, instance_label, room_label, scene_name = data
                verticality = np.zeros(len(xyz), dtype=np.float32)
                boundary_labels = np.zeros(len(xyz), dtype=np.float32)
            elif len(data) == 7:
                xyz, rgb, semantic_label, instance_label, verticality, room_label, scene_name = data
                boundary_labels = np.zeros(len(xyz), dtype=np.float32)
            elif len(data) == 8:
                xyz, rgb, semantic_label, instance_label, verticality, boundary_labels, room_label, scene_name = data
            elif len(data) == 9:
                # 新格式：包含 density，但 density 不参与训练
                xyz, rgb, semantic_label, instance_label, verticality, density, boundary_labels, room_label, scene_name = data
            else:
                raise ValueError(f"Unexpected data format in {filename}: got {len(data)} elements")
            xyz = self._to_numpy(xyz, np.float32)
            rgb = self._to_numpy(rgb, np.float32)
            semantic_label = self._to_numpy(semantic_label, np.int64)
            instance_label = self._to_numpy(instance_label, np.int64)
            verticality = self._to_numpy(verticality, np.float32).reshape(-1)
            boundary_labels = self._to_numpy(boundary_labels, np.float32).reshape(-1)
            return xyz, rgb, semantic_label, instance_label, verticality, boundary_labels
        else:
            if len(data) >= 2:
                xyz, rgb = data[0], data[1]
            else:
                xyz, rgb = torch.load(filename)
            dummy = np.zeros(xyz.shape[0], dtype=np.float32)
            return xyz, rgb, dummy, dummy, dummy, dummy

    # ==================== 数据增强方法 ====================

    def elastic(self, x, gran, mag):
        """弹性变形"""
        blur0 = np.ones((3, 1, 1)).astype('float32') / 3
        blur1 = np.ones((1, 3, 1)).astype('float32') / 3
        blur2 = np.ones((1, 1, 3)).astype('float32') / 3

        bb = np.abs(x).max(0).astype(np.int32) // gran + 3
        noise = [np.random.randn(bb[0], bb[1], bb[2]).astype('float32') for _ in range(3)]
        noise = [scipy.ndimage.filters.convolve(n, blur0, mode='constant', cval=0) for n in noise]
        noise = [scipy.ndimage.filters.convolve(n, blur1, mode='constant', cval=0) for n in noise]
        noise = [scipy.ndimage.filters.convolve(n, blur2, mode='constant', cval=0) for n in noise]
        noise = [scipy.ndimage.filters.convolve(n, blur0, mode='constant', cval=0) for n in noise]
        noise = [scipy.ndimage.filters.convolve(n, blur1, mode='constant', cval=0) for n in noise]
        noise = [scipy.ndimage.filters.convolve(n, blur2, mode='constant', cval=0) for n in noise]
        ax = [np.linspace(-(b - 1) * gran, (b - 1) * gran, b) for b in bb]
        interp = [
            scipy.interpolate.RegularGridInterpolator(ax, n, bounds_error=0, fill_value=0)
            for n in noise
        ]

        def g(x_):
            return np.hstack([i(x_)[:, None] for i in interp])

        return x + g(x) * mag

    def dataAugment(self, xyz, jitter=False, flip=False, rot=False, scale=False, prob=1.0):
        """数据增强"""
        m = np.eye(3)
        if jitter and np.random.rand() < prob:
            m += np.random.randn(3, 3) * 0.1
        if flip and np.random.rand() < prob:
            m[0][0] *= np.random.randint(0, 2) * 2 - 1
        if rot and np.random.rand() < prob:
            theta = np.random.rand() * 2 * math.pi
            m = np.matmul(m, [[math.cos(theta), math.sin(theta), 0],
                              [-math.sin(theta), math.cos(theta), 0], [0, 0, 1]])
        if scale and np.random.rand() < prob:
            scale_factor = np.random.uniform(0.95, 1.05)
            xyz = xyz * scale_factor
        return np.matmul(xyz, m)

    def crop(self, xyz, step=32):
        """裁剪点云"""
        xyz_offset = xyz.copy()
        valid_idxs = xyz_offset.min(1) >= 0
        assert valid_idxs.sum() == xyz.shape[0]
        spatial_shape = np.array([self.voxel_cfg["spatial_shape"][1]] * 3)
        room_range = xyz.max(0) - xyz.min(0)
        while valid_idxs.sum() > self.voxel_cfg["max_npoint"]:
            step_temp = step
            if valid_idxs.sum() > 1e6:
                step_temp = step * 2
            offset = np.clip(spatial_shape - room_range + 0.001, None, 0) * np.random.rand(3)
            xyz_offset = xyz + offset
            valid_idxs = (xyz_offset.min(1) >= 0) * ((xyz_offset < spatial_shape).sum(1) == 3)
            spatial_shape[:2] -= step_temp
        return xyz_offset, valid_idxs

    def getCroppedInstLabel(self, instance_label, valid_idxs):
        """获取裁剪后的实例标签"""
        instance_label = np.asarray(instance_label[valid_idxs], dtype=np.int64).copy()
        valid_instance = instance_label >= 0
        instance_ids = np.unique(instance_label[valid_instance])
        instance_label[~valid_instance] = -100
        if len(instance_ids):
            instance_label[valid_instance] = np.searchsorted(
                instance_ids, instance_label[valid_instance]
            )
        return instance_label

    # ==================== 数据变换 ====================

    def transform_train(self, xyz, rgb, semantic_label, instance_label, verticality, boundary_labels, aug_prob=1.0):
        """训练时的数据变换"""
        xyz_origin = xyz.min(0)
        xyz = xyz - xyz_origin

        xyz_middle = self.dataAugment(xyz, True, True, True, True, aug_prob)
        xyz = xyz_middle * self.voxel_cfg['scale']

        if np.random.rand() < aug_prob:
            xyz = self.elastic(xyz, 6, 40.)
            xyz = self.elastic(xyz, 20, 160.)

        xyz = xyz - xyz.min(0)

        max_tries = 5
        while max_tries > 0:
            xyz_offset, valid_idxs = self.crop(xyz)
            if valid_idxs.sum() >= self.voxel_cfg['min_npoint']:
                xyz = xyz_offset
                break
            max_tries -= 1

        if valid_idxs.sum() < self.voxel_cfg['min_npoint']:
            return None

        xyz = xyz[valid_idxs]
        xyz_middle = xyz_middle[valid_idxs]
        rgb = rgb[valid_idxs]
        semantic_label = semantic_label[valid_idxs]
        instance_label = self.getCroppedInstLabel(instance_label, valid_idxs)
        verticality = verticality[valid_idxs]
        boundary_labels = np.power(
            np.clip(boundary_labels[valid_idxs], 0, 1),
            self.boundary_label_power,
        )

        return xyz, xyz_middle, rgb, semantic_label, instance_label, verticality, boundary_labels

    def transform_test(self, xyz, rgb, semantic_label, instance_label, verticality, boundary_labels):
        """测试时的数据变换"""
        xyz = xyz - xyz.min(0)
        xyz_middle = self.dataAugment(xyz, False, False, False, False)
        xyz = xyz_middle * self.voxel_cfg['scale']
        xyz -= xyz.min(0)

        valid_idxs = np.ones(xyz.shape[0], dtype=bool)
        instance_label = self.getCroppedInstLabel(instance_label, valid_idxs)
        boundary_labels = np.power(
            np.clip(boundary_labels, 0, 1),
            self.boundary_label_power,
        )

        return xyz, xyz_middle, rgb, semantic_label, instance_label, verticality, boundary_labels

    # ==================== 实例信息计算 ====================

    def getInstanceInfo(self, xyz, instance_label, semantic_label):
        """
        获取实例信息 - TreeLearn 风格

        使用树干底部0.5m的点计算实例中心
        """
        pt_offset_label = np.zeros((xyz.shape[0], 3), dtype=np.float32)

        instance_ids = np.unique(instance_label)
        instance_ids = instance_ids[instance_ids >= 0]

        instance_num = 0
        instance_pointnum = []
        instance_cls = []

        for inst_id in instance_ids:
            mask = instance_label == inst_id
            inst_idx = np.where(mask)[0]

            if len(inst_idx) == 0:
                continue

            sem_label = int(semantic_label[inst_idx[0]])

            if sem_label == 1:  # ginkgo
                tree_points = xyz[mask]

                # TreeLearn 风格：使用底部 0.5m 的点计算中心
                if len(tree_points) > self.MIN_POINTS_FOR_ROBUST_Z:
                    min_z = np.partition(tree_points[:, 2], 3)[3]
                else:
                    min_z = tree_points[:, 2].min()

                z_thresh_upper = min_z + self.TREE_BASE_HEIGHT
                bottom_mask = tree_points[:, 2] <= z_thresh_upper
                bottom_points = tree_points[bottom_mask]

                if len(bottom_points) > 0:
                    instance_center = bottom_points.mean(axis=0)
                else:
                    instance_center = tree_points.mean(axis=0)

                pt_offset_label[mask] = instance_center - xyz[mask]

                instance_num += 1
                instance_pointnum.append(int(mask.sum()))
                instance_cls.append(sem_label)

            elif sem_label == 0:  # other/背景
                instance_num += 1
                instance_pointnum.append(int(mask.sum()))
                instance_cls.append(sem_label)

        # 映射：semantic_label=1 -> instance_cls=0, semantic_label=0 -> -100
        instance_cls = [x - 1 if x == 1 else -100 for x in instance_cls]

        return instance_num, instance_pointnum, instance_cls, pt_offset_label

    # ==================== 数据获取 ====================

    def __getitem__(self, index):
        """获取数据项"""
        filename = self.filenames[index]
        scan_id = osp.basename(filename).replace(self.suffix, '')

        data = self.load(filename)

        if self.training:
            data = self.transform_train(*data)
        else:
            data = self.transform_test(*data)

        if data is None:
            return None

        xyz, xyz_middle, rgb, semantic_label, instance_label, verticality, boundary_labels = data

        info = self.getInstanceInfo(xyz_middle, instance_label.astype(np.int32), semantic_label)
        inst_num, inst_pointnum, inst_cls, pt_offset_label = info

        coord = torch.from_numpy(xyz).long()
        coord_float = torch.from_numpy(xyz_middle)
        feat = torch.from_numpy(rgb).float()
        verticality_tensor = torch.from_numpy(verticality).float()
        boundary_tensor = torch.from_numpy(boundary_labels).float()

        if self.training:
            feat += torch.randn(feat.size(1)) * 0.1

        semantic_label = torch.from_numpy(semantic_label)
        instance_label = torch.from_numpy(instance_label)
        pt_offset_label = torch.from_numpy(pt_offset_label)

        return (scan_id, coord, coord_float, feat, semantic_label, instance_label,
                inst_num, inst_pointnum, inst_cls, pt_offset_label, verticality_tensor, boundary_tensor)

    def collate_fn(self, batch):
        """
        Collate 函数

        输出字典包含边界标签和实例信息
        """
        scan_ids = []
        coords = []
        coords_float = []
        feats = []
        semantic_labels = []
        instance_labels = []
        instance_pointnum = []
        instance_cls = []
        pt_offset_labels = []
        verticalities = []
        boundary_labels_list = []

        total_inst_num = 0
        batch_id = 0

        for data in batch:
            if data is None:
                continue

            (scan_id, coord, coord_float, feat, semantic_label, instance_label,
             inst_num, inst_pointnum, inst_cls, pt_offset_label, verticality, boundary_labels) = data

            instance_label[instance_label >= 0] += total_inst_num
            total_inst_num += inst_num

            scan_ids.append(scan_id)
            coords.append(torch.cat([coord.new_full((coord.size(0), 1), batch_id), coord], 1))
            coords_float.append(coord_float)
            feats.append(feat)
            semantic_labels.append(semantic_label)
            instance_labels.append(instance_label)
            instance_pointnum.extend(inst_pointnum)
            instance_cls.extend(inst_cls)
            pt_offset_labels.append(pt_offset_label)
            verticalities.append(verticality)
            boundary_labels_list.append(boundary_labels)

            batch_id += 1

        assert batch_id > 0, 'empty batch'

        if batch_id < len(batch):
            msg = f'batch is truncated from size {len(batch)} to {batch_id}'
            if self.logger:
                self.logger.info(msg)
            else:
                print(msg)

        # 合并数据
        coords = torch.cat(coords, 0)
        batch_idxs = coords[:, 0].int()
        coords_float = torch.cat(coords_float, 0).to(torch.float32)
        feats = torch.cat(feats, 0)
        semantic_labels = torch.cat(semantic_labels, 0).long()
        instance_labels = torch.cat(instance_labels, 0).long()
        instance_pointnum = torch.tensor(instance_pointnum, dtype=torch.int)
        instance_cls = torch.tensor(instance_cls, dtype=torch.long)
        pt_offset_labels = torch.cat(pt_offset_labels).float()
        verticalities = torch.cat(verticalities, 0).float()
        boundary_labels = torch.cat(boundary_labels_list, 0).float()

        spatial_shape = np.clip(
            coords.max(0)[0][1:].numpy() + 1, self.voxel_cfg['spatial_shape'][0], None)

        # 体素化
        try:
            from softgroup.ops import voxelization_idx
            voxel_coords, v2p_map, p2v_map = voxelization_idx(coords, batch_id)
        except ImportError as exc:
            raise ImportError(
                "Boundary training requires the original SoftGroup voxelization_idx extension; "
                "a one-point-per-voxel fallback would change the experiment."
            ) from exc

        return {
            'scan_ids': scan_ids,
            'coords': coords,
            'batch_idxs': batch_idxs,
            'voxel_coords': voxel_coords,
            'p2v_map': p2v_map,
            'v2p_map': v2p_map,
            'coords_float': coords_float,
            'feats': feats,
            'semantic_labels': semantic_labels,
            'instance_labels': instance_labels,
            'instance_pointnum': instance_pointnum,
            'instance_cls': instance_cls,
            'pt_offset_labels': pt_offset_labels,
            'spatial_shape': spatial_shape,
            'batch_size': batch_id,
            'verticality': verticalities,
            'boundary_labels': boundary_labels,
            'sem2ins_classes': self.SEM2INS_CLASSES,
        }


